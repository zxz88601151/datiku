def _make_opts(correct: Any, wrongs_pool: List[Any]) -> List[Dict]:
    """生成4个选项，随机排列。"""
    wrongs = [str(w) for w in wrongs_pool[:3] if str(w) != str(correct)]
    while len(wrongs) < 3:
        wrongs.append(str(int(str(correct)) + len(wrongs) + 2) if str(correct).isdigit() else f"其他选项{len(wrongs)+1}")
    all_c = [str(correct)] + wrongs[:3]
    random.shuffle(all_c)
    return [{"label": chr(65+i), "text": c, "correct": c == str(correct)} for i, c in enumerate(all_c)]


def _make_q(subject, grade, chapter, knowledge, diff, errors, content, answer, analysis, subtype, id_suffix):
    opts = [o for o in answer if isinstance(answer, list)][0] if isinstance(answer, list) else answer
    if not isinstance(answer, list):
        opts = answer
        answer_label = next(o["label"] for o in opts if o["correct"])
    else:
        opts = answer
        answer_label = next(o["label"] for o in opts if o["correct"])
    
    return {
        "id": f"{subject}{grade}_{chapter}_{subtype}_{id_suffix}",
        "type": "选择题",
        "subject": subject,
        "grade": grade,
        "chapter": chapter,
        "knowledge": [knowledge] if isinstance(knowledge, str) else knowledge,
        "difficulty": diff,
        "exam_weight": diff,
        "subtype": subtype,
        "error_tags": errors or [],
        "content": content,
        "answer": answer_label,
        "analysis": analysis,
        "options": opts,
    }


def _make_simple_q(subject, grade, chapter, knowledge, diff, errors, content, correct_ans, wrongs, analysis, subtype, sid):
    opts = _make_opts(correct_ans, wrongs)
    ans_label = next(o["label"] for o in opts if o["correct"])
    return {
        "id": f"{subject}{grade}_{chapter}_{subtype}_{sid}",
        "type": "选择题",
        "subject": subject,
        "grade": grade,
        "chapter": chapter,
        "knowledge": [knowledge] if isinstance(knowledge, str) else knowledge,
        "difficulty": diff,
        "exam_weight": diff,
        "subtype": subtype,
        "error_tags": errors or [],
        "content": content,
        "answer": ans_label,
        "analysis": analysis,
        "options": opts,
    }


