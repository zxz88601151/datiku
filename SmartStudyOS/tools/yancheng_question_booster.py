def get_existing_ids(questions: List[Dict]) -> set:
    """获取已有题目的id集合。"""
    return {q.get("id", "") for q in questions}


def main():
    print("=" * 60)
    print("盐城数据题目增强器 — 补充各年级各科题目")
    print("=" * 60)
    
    boosters = {
        ("数学", "yancheng_math"): MATH_BOOSTER,
        ("语文", "yancheng_chinese"): CHINESE_BOOSTER,
        ("英语", "yancheng_english"): ENGLISH_BOOSTER,
        ("科学", "yancheng_science"): SCIENCE_BOOSTER,
    }
    
    total_boosted = 0
    
    for (subject, subdir), booster in boosters.items():
        print(f"\n--- {subject} ---")
        for grade_label, items in sorted(booster.items(), key=lambda x: int(x[0].replace("年级","").replace("一","1").replace("二","2").replace("三","3").replace("四","4").replace("五","5").replace("六","6").replace("年",""))):
            # 中文年级标签 → 数字文件名
            grade_num_map = {"一年级":"1","二年级":"2","三年级":"3","四年级":"4","五年级":"5","六年级":"6"}
            grade_num = grade_num_map.get(grade_label, "1")
            # 读取现有题目文件
            q_path = QUESTIONS_DIR / subdir / f"grade{grade_num}.json"
            if not q_path.exists():
                print(f"  ⚠ 找不到 {q_path}，跳过")
                continue
            
            with open(q_path, "r", encoding="utf-8") as f:
                data = json.load(f)
            
            existing = data.get("questions", [])
            existing_ids = get_existing_ids(existing)
            
            count_before = len(existing)
            added = 0
            
            for chapter, knowledge, content, correct_ans, wrong_choices in items:
                # 为每个知识点生成若干题目
                diff = 3  # 中等难度
                
                # 生成选项
                opts = _make_opts(correct_ans, wrong_choices)
                ans_label = next(o["label"] for o in opts if o["correct"])
                
                new_id = f"{subject}{grade_label}_{chapter}_booster_{added+1}"
                if new_id in existing_ids:
                    continue
                
                q = {
                    "id": new_id,
                    "type": "选择题",
                    "subject": subject,
                    "grade": grade_label,
                    "chapter": chapter,
                    "knowledge": [knowledge],
                    "difficulty": diff,
                    "exam_weight": diff,
                    "subtype": "综合",
                    "error_tags": [],
                    "content": content,
                    "answer": ans_label,
                    "analysis": f"正确答案是「{correct_ans}」。",
                    "options": opts,
                }
                existing.append(q)
                added += 1
            
            if added > 0:
                # 重排序 — 确保id唯一
                for i, q in enumerate(existing):
                    pass
                
                data["questions"] = existing
                with open(q_path, "w", encoding="utf-8") as f:
                    json.dump(data, f, ensure_ascii=False, indent=2)
                print(f"  ✓ {grade_label}: {count_before} → {len(existing)} 题 (+{added})")
                total_boosted += added
            else:
                print(f"  - {grade_label}: {len(existing)} 题（无新增）")
    
    print("\n" + "=" * 60)
    print(f"增强完成！总计补充 {total_boosted} 道题目。")
    print("=" * 60)


if __name__ == "__main__":
    main()
